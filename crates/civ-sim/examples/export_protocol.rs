//! Run from the workspace root: cargo run -p civ-sim --example export_protocol.
use civ_sim::{
    protocol::{ClientMessage, ServerMessage, PROTOCOL_VERSION},
    RuleTables, Settings,
};
use std::{collections::HashMap, error::Error, path::PathBuf};
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn Error>> {
    let dir = std::env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../web/src/engine/generated")
        });
    std::fs::create_dir_all(&dir)?;
    let mut previous_ts = HashMap::new();
    for entry in std::fs::read_dir(&dir)? {
        let path = entry?.path();
        if path.extension().is_some_and(|extension| extension == "ts") {
            previous_ts.insert(path.clone(), std::fs::read_to_string(path)?);
        }
    }
    let cfg = Config::default().with_out_dir(&dir);
    ClientMessage::export_all(&cfg)?;
    ServerMessage::export_all(&cfg)?;
    Settings::export_all(&cfg)?;
    RuleTables::export_all(&cfg)?;
    // ts-rs leaves spaces before field doc comments. Clean changed bindings without
    // rewriting unrelated generated files that already contain those spaces.
    for entry in std::fs::read_dir(&dir)? {
        let path = entry?.path();
        if !path.extension().is_some_and(|extension| extension == "ts") {
            continue;
        }
        let generated = std::fs::read_to_string(&path)?;
        if previous_ts.get(&path) == Some(&generated) {
            continue;
        }
        let normalized = format!(
            "{}\n",
            generated
                .lines()
                .map(str::trim_end)
                .collect::<Vec<_>>()
                .join("\n")
        );
        if normalized != generated {
            std::fs::write(path, normalized)?;
        }
    }
    std::fs::write(
        dir.join("server-message.schema.json"),
        serde_json::to_string_pretty(&schemars::schema_for!(ServerMessage))?,
    )?;
    std::fs::write(
        dir.join("client-message.schema.json"),
        serde_json::to_string_pretty(&schemars::schema_for!(ClientMessage))?,
    )?;
    // The bundled rules, for menus drawn before any session opens (web/src/engine/rules.ts).
    let rules = civ_sim::content::load()?;
    std::fs::write(
        dir.join("rule-tables.json"),
        serde_json::to_string(&civ_sim::tables(&rules))?,
    )?;
    std::fs::write(dir.join("version.ts"), format!("// Generated by civ-sim; do not edit.\nexport const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n"))?;
    Ok(())
}
