//! Run from the workspace root: cargo run -p civ-sim --example export_protocol.
use civ_sim::{
    protocol::{ClientMessage, ServerMessage, PROTOCOL_VERSION},
    RuleTables, Settings,
};
use std::{error::Error, path::PathBuf};
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn Error>> {
    let dir = std::env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../web/src/engine/generated")
        });
    std::fs::create_dir_all(&dir)?;
    let cfg = Config::default().with_out_dir(&dir);
    ClientMessage::export_all(&cfg)?;
    ServerMessage::export_all(&cfg)?;
    Settings::export_all(&cfg)?;
    RuleTables::export_all(&cfg)?;
    std::fs::write(
        dir.join("server-message.schema.json"),
        serde_json::to_string_pretty(&schemars::schema_for!(ServerMessage))?,
    )?;
    std::fs::write(
        dir.join("client-message.schema.json"),
        serde_json::to_string_pretty(&schemars::schema_for!(ClientMessage))?,
    )?;
    std::fs::write(dir.join("version.ts"), format!("// Generated by civ-sim; do not edit.\nexport const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n"))?;
    Ok(())
}
