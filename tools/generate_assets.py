#!/usr/bin/env python3
"""Generate typed sprite IDs from the shipped libGDX atlases.

Referencing a sprite that isn't packed becomes a compile error instead of a
missing-texture bug at runtime.
"""
import re, json, pathlib, collections

ROOT   = pathlib.Path("../Unciv")
ASSETS = ROOT/"android/assets"
RS_OUT = ROOT/"civ-core-rs/src/generated"
TS_OUT = ROOT/"civ-web/src/generated"
for d in (RS_OUT, TS_OUT): d.mkdir(parents=True, exist_ok=True)

INDENTED = re.compile(r'^\s')

def parse_atlas(path):
    """libGDX atlas: page header, then `RegionName` lines with indented attrs."""
    regions, page = [], None
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if not line.strip():
            page = None                       # blank line starts a new page block
            continue
        if INDENTED.match(line):
            continue                          # attribute of the current region
        if page is None:
            page = line.strip()               # first non-indented line = page png
            continue
        regions.append(line.strip())
    return regions

atlases = sorted(ASSETS.glob("*.atlas"))
by_region = collections.OrderedDict()
for a in atlases:
    for r in parse_atlas(a):
        by_region.setdefault(r, []).append(a.stem)

def ident(name):
    """`CityStateIcons/Cultured` -> `CityStateIconsCultured` (Rust enum variant case)."""
    parts = [w for w in re.split(r'[^0-9A-Za-z]+', name) if w]
    out = []
    for w in parts:
        out.append(w if (w[:1].isupper() and not w.isupper()) else w[:1].upper() + w[1:])
    s = "".join(out)
    return ('N' + s) if s[:1].isdigit() else s

# identifier collisions must be resolved deterministically, not silently
idents, used = {}, {}
for region in by_region:
    base = ident(region)
    n = used.get(base, 0); used[base] = n + 1
    idents[region] = base if n == 0 else f"{base}_{n+1}"

groups = collections.Counter(r.split('/')[0] if '/' in r else '(root)' for r in by_region)

# ---- Rust -------------------------------------------------------------------
L = ["// @generated by tools/generate_assets.py from android/assets/*.atlas — do not edit.",
     "//! Every sprite packed into the shipped atlases, as a closed set.",
     "",
     "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]",
     "pub enum Sprite {"]
L += [f"    {idents[r]}," for r in by_region]
L += ["}", "",
      "impl Sprite {",
      f"    pub const ALL: [Sprite; {len(by_region)}] = [",
      *[f"        Sprite::{idents[r]}," for r in by_region],
      "    ];", "",
      "    /// Atlas region name, e.g. `\"CityStateIcons/Cultured\"`.",
      "    pub fn region(self) -> &'static str {",
      "        match self {"]
L += [f'            Sprite::{idents[r]} => "{r}",' for r in by_region]
L += ["        }", "    }", "",
      "    /// Which atlas file packs this region.",
      "    pub fn atlas(self) -> &'static str {",
      "        match self {"]
L += [f'            Sprite::{idents[r]} => "{by_region[r][0]}",' for r in by_region]
L += ["        }", "    }", "",
      "    pub fn from_region(s: &str) -> Option<Sprite> {",
      "        Sprite::ALL.into_iter().find(|v| v.region() == s)",
      "    }", "}"]
(RS_OUT/"assets.rs").write_text("\n".join(L) + "\n")

# ---- TypeScript -------------------------------------------------------------
T = ["// @generated by tools/generate_assets.py from android/assets/*.atlas — do not edit.",
     "", "export const SPRITES = {"]
T += [f'  {json.dumps(idents[r])}: {json.dumps(r)},' for r in by_region]
T += ["} as const;", "",
      "export type SpriteId = keyof typeof SPRITES;",
      "export type SpriteRegion = (typeof SPRITES)[SpriteId];", "",
      "export const ATLAS_OF: Record<SpriteId, string> = {"]
T += [f'  {json.dumps(idents[r])}: {json.dumps(by_region[r][0])},' for r in by_region]
T += ["};", "",
      f"export const ATLASES = {json.dumps(sorted(a.stem for a in atlases))} as const;"]
(TS_OUT/"assets.ts").write_text("\n".join(T) + "\n")

print(f"atlases        {len(atlases)}")
print(f"regions        {len(by_region)} unique")
print(f"collisions     {sum(1 for k,v in used.items() if v>1)} identifier stems disambiguated")
print("top groups     " + ", ".join(f"{g}:{n}" for g,n in groups.most_common(6)))
